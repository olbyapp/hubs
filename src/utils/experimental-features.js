import { qsGet } from "./qs_truthy";

// Флаги фич кастомного клиента.
//
// Здесь же живут гейты для механик, которые ещё обкатываются. Гейт по админу
// делается через configs.isAdmin() — внутри комнаты его выставляет hub-channel.js
// в updatePermissions() из perms-JWT. Важно: флаг приезжает асинхронно и
// обновляется по таймеру, поэтому читать его надо покадрово, а не один раз в
// init(). И это гейт видимости, а не безопасности: perms-токен на клиенте не
// верифицируется.

// Прилипание медиа к поверхностям при размещении. Обкатано на админе и с
// 2026-08-17 включено для всех.
export function snapPlacementEnabled() {
  // ?snap=0 — аварийный выход и способ сравнить со старым поведением, не трогая
  // сборку. Оставлен доступным всем: если механика где-то мешает, человек может
  // отключить её себе сам, не дожидаясь выкатки.
  return qsGet("snap") !== "0";
}
