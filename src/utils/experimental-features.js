import configs from "./configs";
import { qsGet } from "./qs_truthy";

// Опытные механики, которые пока видит только администратор инстанса.
//
// Внутри комнаты configs.isAdmin() выставляет hub-channel.js в updatePermissions()
// из perms-JWT. Делает он это асинхронно: на старте флаг всегда false и становится
// true только после джойна в hub-канал, а дальше перевыставляется при каждом
// обновлении прав. Поэтому читать его надо на каждом кадре, а не один раз в init().
//
// Это гейт видимости, а не безопасности — perms-токен на клиенте не верифицируется,
// так что кто угодно может включить фичу себе из devtools. Задача здесь только в том,
// чтобы недоделанная механика не попалась коллегам на глаза.

export function snapPlacementEnabled() {
  if (!configs.isAdmin()) return false;
  // ?snap=0 — сравнить старое и новое поведение в двух вкладках, не разлогиниваясь.
  // Параметр умеет только выключать, поэтому фичу он никому лишнему не откроет.
  return qsGet("snap") !== "0";
}
